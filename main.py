# 1. Text Type


# String
x = "hello world"
print(f"Type of x is {type(x)}")


# 2. Numeric Type


# Interger
c = 911
print(f"Type of c is {type(c)}")

# Float
z = 1.67
print(f"Type of z is {type(z)}")

# Complex
m = 30j
print(f"Type of m is {type(m)}")


# 3. Sequence Type


# List
b = ["String","Interger","Float","Bollean"]
print(f"Type of b is {type(b)}")

# Tuple
n = ("String","Interger","Float","Bollean")
print(f"Type of n is {type(n)}")


# 4. Maping Type


# Dictnory
l = {"Name":"ethan","Age":"5"}
print(f"Type of l is {type(l)}")


# 5. Boolean Type


# Boolean
v = True 
print(f"Type of v is {type(v)}")